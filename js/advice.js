function getRandom(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

function getAdviceForPhase(phase) {
  const data = ADVICE[phase] || ADVICE.follicular;
  return {
    plans: getRandom(data.plans),
    advice: getRandom(data.advice),
    cheer: getRandom(data.cheer)
  };
}

